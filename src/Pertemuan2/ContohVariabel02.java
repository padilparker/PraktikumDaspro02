public class ContohVariabel02 {
    public static void main(String[] args) {
        String hobi = "Bermain petak umpet";
        boolean isPandai = true;
        char jenisKelamin = 'L';
        byte umurSayaSekarang = 20;
        double ipk = 3.24, tinggi = 1.78;

        System.out.println("Salah satu hobi saya adalah " + hobi);
        System.out.println("Apakah saya pandai? " + isPandai);
        System.out.println("Jenis kelamin: " + jenisKelamin);
        System.out.println("Umur saya: " + umurSayaSekarang);
        System.out.println("IPK saya: " + ipk);
        System.out.println("Tinggi saya: " + tinggi);
        System.out.printf("saya beripk %s, dengan tinggi badan %s", ipk,tinggi);
    }
    
}
